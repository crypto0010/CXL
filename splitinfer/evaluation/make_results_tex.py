#!/usr/bin/env python3
"""Generate paper/results.tex — every number in the paper as a LaTeX macro,
read from the JSON artifacts.  Missing artifacts produce \\NA so the paper
still compiles and the gap is visible.  Each macro's provenance
(MEASURED / EMULATED / MODELLED) is encoded in its name prefix:
  \\M...  measured on hardware     \\E...  emulator     \\C...  cost model / analytic
"""
import json, math, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
R = os.path.join(ROOT, "evaluation", "experiments", "results")
OUT = os.path.join(ROOT, "paper", "results.tex")

lines = ["% AUTO-GENERATED by evaluation/make_results_tex.py — do not edit", r"\newcommand{\NA}{\textcolor{red}{n/a}}"]


_DIG = {"0": "zero", "1": "one", "2": "two", "3": "three", "4": "four", "5": "five", "6": "six", "7": "seven", "8": "eight", "9": "nine"}


def macro(name, val, fmt="{:.2f}"):
    name = "".join(_DIG.get(ch, ch) for ch in name)
    name = re.sub(r"[^A-Za-z]", "", name)
    if val is None or (isinstance(val, float) and (math.isnan(val) or math.isinf(val))):
        lines.append(f"\\newcommand{{\\{name}}}{{\\NA}}")
    else:
        s = fmt.format(val) if not isinstance(val, str) else val
        lines.append(f"\\newcommand{{\\{name}}}{{{s}}}")


def load(p):
    try:
        with open(p) as f: return json.load(f)
    except Exception: return None


def num(s):
    """Human number: 1234 -> 1,234 ; 0.0123 -> 0.012"""
    if s is None: return None
    if abs(s) >= 100: return f"{s:,.0f}"
    if abs(s) >= 10: return f"{s:.1f}"
    if abs(s) >= 1: return f"{s:.2f}"
    return f"{s:.3f}"


# ── E2 v2 cells ────────────────────────────────────────────────────────
for tag, fn in (("Emul", "e2_v2_dlrm_emul_uart.json"), ("Usb", "e2_v2_dlrm_usb.json")):
    d = load(os.path.join(R, "e2", fn))
    cells = (d or {}).get("cells", {})
    for cell in ("B1_ort_fp32_cpu", "B2_ort_int8_cpu", "B3_trt_fp16_gpu", "B4_trt_int8_gpu", "SI_host", "SI_nmc", "SI_pool", "SI_pool_warm"):
        c = cells.get(cell) or {}
        st = (c.get("result") or {}).get("stats") or (c.get("result") or {})
        short = cell.replace("_", "")
        pre = "M" if tag == "Usb" or not cell.startswith("SI_") or cell == "SI_host" else "E"
        ok = c.get("status") == "ok"
        macro(f"{pre}{tag}{short}Median", num(st.get("median_ms")) if ok else None, "{}")
        macro(f"{pre}{tag}{short}Pninenine", num(st.get("p99_ms")) if ok else None, "{}")
        macro(f"{pre}{tag}{short}CV", st.get("cv_pct") if ok else None, "{:.0f}")
        macro(f"{pre}{tag}{short}Power", c.get("power", {}).get("rails", {}).get("VDD_IN", {}).get("mean_mw") if ok else None, "{:,.0f}")
        macro(f"{pre}{tag}{short}Samples", c.get("power_samples") if ok else None, "{:d}")
        macro(f"{pre}{tag}{short}Energy", (c.get("energy_per_inf_J") or 0) * 1000 if ok else None, "{:.2f}")
        link = (c.get("result") or {}).get("link") or {}
        macro(f"{pre}{tag}{short}LinkOut", link.get("bytes_out"), "{:,.0f}")
        macro(f"{pre}{tag}{short}LinkIn", link.get("bytes_in"), "{:,.0f}")
        macro(f"{pre}{tag}{short}Msgs", link.get("msgs"), "{:.0f}")
        macro(f"{pre}{tag}{short}Faults", link.get("faults"), "{:.0f}")
        macro(f"{pre}{tag}{short}Prepare", ((c.get("result") or {}).get("prepare_ms") or 0) / 1000, "{:.0f}")
        corr = (c.get("result") or {}).get("correctness") or {}
        macro(f"{pre}{tag}{short}BitExact", f"{corr.get('bit_exact', 0)}/{corr.get('total', 0)}" if corr else None, "{}")
        macro(f"{pre}{tag}{short}NormErr", corr.get("max_norm_err_fp32", None), "{:.3f}")
        macro(f"{pre}{tag}{short}Status", c.get("status", "missing"), "{}")

# ── Board session (measured; nmc_exact n=3, pool_exact n=1) ───────────────
import glob
logs = sorted(glob.glob(os.path.join(R, "board_session_*.log")))
def _block(text, name, nxt):
    a = text.find(f"===== {name} ====="); b = text.find(f"===== {nxt} =====", a + 1)
    return text[a:b] if a >= 0 and b > a else ""
for lg in logs[-1:]:
    txt = open(lg, errors="replace").read()
    for cell, nxt, tag in (("nmc_exact", "pool_exact", "SInmcexact"), ("pool_exact", "calibrate", "SIpoolcold")):
        blk = _block(txt, cell, nxt)
        m = re.search(r"median ([\d.]+)\s+mean ([\d.]+)\s+sd ([\d.]+).*?p99 ([\d.]+)", blk)
        c = re.search(r"correctness: (\d+)/(\d+) bit-exact.*?normalised ([\d.]+)", blk)
        lk = re.search(r"([\d.]+) msgs(?:, ([\d.]+) faults, ([\d.]+) pages, ([\d.]+) fetch RTTs)?", blk)
        ok = "exit 0" in blk
        macro(f"MUsb{tag}Median", num(float(m.group(1))) if (m and ok) else None, "{}")
        macro(f"MUsb{tag}Pninenine", num(float(m.group(4))) if (m and ok) else None, "{}")
        macro(f"MUsb{tag}BitExact", f"{c.group(1)}/{c.group(2)}" if c else None, "{}")
        macro(f"MUsb{tag}NormErr", float(c.group(3)) if c else None, "{:.3f}")
        macro(f"MUsb{tag}Msgs", float(lk.group(1)) if lk else None, "{:.0f}")
        macro(f"MUsb{tag}Faults", float(lk.group(2)) if (lk and lk.group(2)) else None, "{:.0f}")
        macro(f"MUsb{tag}Pages", float(lk.group(3)) if (lk and lk.group(3)) else None, "{:.0f}")
    macro("MUsbSessionLog", os.path.basename(lg).replace("_", "\\_"), "{}")
cal = load(os.path.join(ROOT, "evaluation", "calibration", "uart_measured.json")) or {}
macro("MLinkRtt", (cal.get("barrier_rtt_ms") or {}).get("median"), "{:.1f}")
macro("MLinkBw", (cal.get("fit") or {}).get("link_bw_bytes_per_s"), "{:,.0f}")
cal16 = load(os.path.join(ROOT, "evaluation", "calibration", "uart_measured_v1bit.json")) or {}
macro("MLinkRttDefaultTimer", (cal16.get("barrier_rtt_ms") or {}).get("median"), "{:.1f}")

# ── E6 crossover ───────────────────────────────────────────────────────
e6 = load(os.path.join(R, "e6", "dlrm_crossover_emul.json"))
for pt in (e6 or {}).get("points", []):
    name = pt["link"]
    for cfg in ("nmc", "pool_pf1", "pool_pf64", "pool_pf512", "pool_warm"):
        c = pt.get(cfg) or {}
        st = c.get("stats") or {}
        macro(f"Esix{name}{cfg.replace('_','')}", num(st.get("median_ms")) if c.get("status") == "ok" else None, "{}")
        macro(f"Esix{name}{cfg.replace('_','')}Faults", (c.get("link") or {}).get("fetch_rtts"), "{:.0f}")

# ── E7 streaming capacity ──────────────────────────────────────────────
e7 = load(os.path.join(R, "e7", "mlp_8x100mb_streaming_emul.json")) or {}
for cell, c in e7.get("cells", {}).items():
    st = c.get("stats", {})
    macro(f"Eseven{cell}Median", num(st.get("median_ms")), "{}")
    macro(f"Eseven{cell}Stream", num(c.get("weight_stream_ms")), "{}")
    macro(f"Eseven{cell}BitExact", f"{c.get('correctness', {}).get('bit_exact', 0)}/{c.get('correctness', {}).get('total', 0)}", "{}")
    macro(f"Eseven{cell}NormErr", c.get("correctness", {}).get("max_norm_err_fp32"), "{:.3f}")

# ── TRT standalone ─────────────────────────────────────────────────────
for p in ("fp16", "int8"):
    d = load(os.path.join(R, "e2", f"dlrm_trt_{p}.json")) or {}
    st = d.get("stats", {})
    macro(f"MTrt{p}Median", st.get("median_ms"), "{:.3f}")
    macro(f"MTrt{p}Power", (d.get("power") or {}).get("rails", {}).get("VDD_IN", {}).get("mean_mw"), "{:,.0f}")

# ── Capacity / partitioner (modelled) ──────────────────────────────────
for tag, fn in (("Dlrm", "dlrm_small_manifest.json"), ("MlpEight", "mlp_8x100mb_manifest.json")):
    d = load(os.path.join(ROOT, "evaluation", "lowered", fn)) or {}
    s = d.get("summary", {})
    macro(f"C{tag}Latency", s.get("estimated_latency_ms"), "{:,.0f}")
    macro(f"C{tag}WeightsMiB", (s.get("total_weight_bytes") or 0) / 2**20, "{:.1f}")
    pc = s.get("placements", {})
    macro(f"C{tag}NumGpu", pc.get("gpu"), "{:d}"); macro(f"C{tag}NumPool", pc.get("pool"), "{:d}"); macro(f"C{tag}NumFpga", pc.get("fpga"), "{:d}")
    macro(f"C{tag}Transfers", s.get("num_transfers"), "{:d}")
    for k, v in (s.get("breakdown_ms") or {}).items():
        macro(f"C{tag}Bd{k.replace('_','')}", v, "{:,.1f}")
    hw = d.get("hardware_params") or {}
    macro(f"C{tag}LinkBw", hw.get("link_bw_bytes_per_s"), "{:,.0f}")
    macro(f"C{tag}Rtt", hw.get("link_rtt_ms"), "{:.1f}")
    macro(f"C{tag}FpgaGops", hw.get("fpga_int8_gops"), "{:.3f}")

# ── Lowered programs ───────────────────────────────────────────────────
for tag, dn in (("Dlrm", "dlrm_small"), ("MlpEight", "mlp_8x100mb")):
    d = load(os.path.join(ROOT, "evaluation", "lowered", dn, "program.json")) or {}
    macro(f"P{tag}ImageMiB", (d.get("ddr2", {}).get("image_bytes") or 0) / 2**20, "{:.1f}")
    macro(f"P{tag}LayoutMiB", (d.get("ddr2", {}).get("layout_end") or 0) / 2**20, "{:.1f}")
    macro(f"P{tag}SlotMiB", (d.get("ddr2", {}).get("slot_bytes") or 0) / 2**20, "{:.1f}")
    macro(f"P{tag}TotalWeightMiB", (d.get("ddr2", {}).get("total_weight_bytes") or 0) / 2**20, "{:.1f}")
    macro(f"P{tag}NormErr", (d.get("vectors", {}).get("max_norm_err_vs_fp32")), "{:.3f}")
    macro(f"P{tag}Layers", len(d.get("layers", [])), "{:d}")

# ── v1 capacity sweep (measured, kept) ─────────────────────────────────
cap = load(os.path.join(R, "e1", "capacity_sweep", "capacity_unlock_summary.json")) or {}
for m in cap.get("baseline_fp32_measurements", []):
    tag = f"{m['model_size_gb']:.2f}".replace(".", "p")
    macro(f"MCap{tag}Lat", m.get("b1_inference_ms"), "{:,.0f}")
    macro(f"MCap{tag}Rss", m.get("b1_peak_rss_mb"), "{:,.0f}")
    macro(f"MCap{tag}Status", m.get("b1_status", ""), "{}")

os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, "w") as f: f.write("\n".join(lines) + "\n")
na = sum(1 for l in lines if "\\NA}" in l)
print(f"wrote {OUT}: {len(lines)-2} macros, {na} n/a")
